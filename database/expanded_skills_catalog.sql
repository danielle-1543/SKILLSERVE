INSERT OR IGNORE INTO accounts_skillcategory (name, slug, description)
SELECT DISTINCT seed.category_name, seed.category_slug, ''
FROM skillserve_catalog_import AS seed
WHERE NOT EXISTS (
    SELECT 1 FROM accounts_skillcategory AS current
    WHERE LOWER(current.name) = LOWER(seed.category_name)
       OR current.slug = seed.category_slug
);

INSERT OR IGNORE INTO accounts_specialtytag (category_id, name)
SELECT category.id, seed.specialty_name
FROM skillserve_catalog_import AS seed
JOIN accounts_skillcategory AS category
  ON category.id = (
    SELECT match.id FROM accounts_skillcategory AS match
    WHERE match.slug = seed.category_slug
       OR LOWER(match.name) = LOWER(seed.category_name)
    ORDER BY CASE WHEN match.slug = seed.category_slug THEN 0 ELSE 1 END, match.id
    LIMIT 1
  )
WHERE NOT EXISTS (
    SELECT 1 FROM accounts_specialtytag AS current
    WHERE current.category_id = category.id
      AND LOWER(current.name) = LOWER(seed.specialty_name)
);

